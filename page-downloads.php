            <script>
                $(document).ready(function () {
                    $("#main-menu #t-downloads, #f-downloads").addClass('active');

                    var leadVerified = <?php echo !empty($_SESSION['brochure_lead_verified']) ? 'true' : 'false'; ?>;

                    var keyAliases = {
                        'cooler-mixer': 'heater-cooler-mixer',
                        'high-speed-heater-cooler-mixer': 'heater-cooler-mixer',
                        'lab-mixer': 'laboratory-mixer',
                        'flexible-spiral-conveyor': 'spiral-conveyor',
                        'flexible-spiral-conveyors': 'spiral-conveyor',
                        'gyro-vibrating-screen': 'gyro-vibrating-sieve'
                    };

                    function triggerDirectDownload(fileUrl) {
                        var a = document.createElement('a');
                        a.href = fileUrl;
                        var filename = fileUrl.split('/').pop().split('?')[0];
                        if (filename) {
                            a.setAttribute('download', decodeURIComponent(filename));
                        }
                        a.target = '_blank';
                        document.body.appendChild(a);
                        a.click();
                        setTimeout(function () {
                            if (a.parentNode) {
                                a.parentNode.removeChild(a);
                            }
                        }, 200);
                    }

                    function openLeadModal(key, title, file) {
                        $('#leadAlertError').hide().text('');
                        $('#leadAlertSuccess').hide().text('');
                        $('#modalBrochureTitle').text(title);
                        $('#hiddenBrochureTitle').val(title);
                        $('#hiddenBrochureFile').val(file);
                        $('#hiddenBrochureKey').val(key);
                        $('#btnSubmitLead').prop('disabled', false).html('<i class="fa fa-download" style="margin-right:6px;"></i> Download Brochure');
                        $('#brochureLeadModal').modal('show');
                    }

                    // Download button click handler
                    $('.btn-trigger-brochure').on('click', function (e) {
                        e.preventDefault();
                        var key = $(this).attr('data-brochure-key');
                        var title = $(this).attr('data-brochure-title');
                        var file = $(this).attr('data-brochure-file');

                        if (leadVerified) {
                            triggerDirectDownload(file);
                        } else {
                            openLeadModal(key, title, file);
                        }
                    });

                    // Form submission AJAX
                    $('#brochureLeadForm').on('submit', function (e) {
                        e.preventDefault();
                        var $btn = $('#btnSubmitLead');
                        var $err = $('#leadAlertError');
                        var $succ = $('#leadAlertSuccess');

                        $err.hide().text('');
                        $succ.hide().text('');

                        var name = $.trim($('#lead_name').val());
                        var email = $.trim($('#lead_email').val());
                        var phone = $.trim($('#lead_phone').val());

                        if (!name) {
                            $err.text('Please enter your full name.').fadeIn();
                            $('#lead_name').focus();
                            return false;
                        }
                        if (!email) {
                            $err.text('Please enter your work email.').fadeIn();
                            $('#lead_email').focus();
                            return false;
                        }
                        if (!phone) {
                            $err.text('Please enter your contact phone number.').fadeIn();
                            $('#lead_phone').focus();
                            return false;
                        }

                        $btn.prop('disabled', true).html('<i class="fa fa-spinner fa-spin"></i> Processing & Preparing Download...');

                        $.ajax({
                            url: '<?php echo $GLBHost; ?>process-brochure-lead.php',
                            type: 'POST',
                            data: $(this).serialize(),
                            dataType: 'json',
                            success: function (res) {
                                if (res && res.success) {
                                    leadVerified = true;
                                    $succ.html('<i class="fa fa-check-circle"></i> Thank you! Your brochure download is starting now...').fadeIn();
                                    var dlUrl = res.downloadUrl || $('#hiddenBrochureFile').val();
                                    
                                    setTimeout(function () {
                                        triggerDirectDownload(dlUrl);
                                    }, 400);

                                    setTimeout(function () {
                                        $('#brochureLeadModal').modal('hide');
                                    }, 2200);
                                } else {
                                    $btn.prop('disabled', false).html('<i class="fa fa-download" style="margin-right:6px;"></i> Download Brochure');
                                    $err.text((res && res.message) ? res.message : 'An error occurred. Please try again.').fadeIn();
                                }
                            },
                            error: function () {
                                $btn.prop('disabled', false).html('<i class="fa fa-download" style="margin-right:6px;"></i> Download Brochure');
                                $err.text('Unable to submit inquiry at this moment. Please try again or contact us directly.').fadeIn();
                            }
                        });
                    });

                    // Check if query parameter "brochure" exists in URL
                    var urlParams = new URLSearchParams(window.location.search);
                    var brochureParam = urlParams.get('brochure');
                    if (brochureParam) {
                        brochureParam = brochureParam.toLowerCase().replace(/[^a-z0-9\-]/g, '');
                        if (keyAliases[brochureParam]) {
                            brochureParam = keyAliases[brochureParam];
                        }

                        var $targetRow = $('#item-' + brochureParam);
                        if ($targetRow.length) {
                            // Smooth scroll to machine card
                            $('html, body').animate({
                                scrollTop: $targetRow.offset().top - 120
                            }, 600);

                            // Highlight machine card
                            $targetRow.addClass('row-active-focus');

                            // Find download button for this machine
                            var $btn = $targetRow.find('.btn-trigger-brochure');
                            var key = $btn.attr('data-brochure-key');
                            var title = $btn.attr('data-brochure-title');
                            var file = $btn.attr('data-brochure-file');

                            // Open lead modal or trigger download
                            setTimeout(function () {
                                if (leadVerified) {
                                    triggerDirectDownload(file);
                                } else {
                                    openLeadModal(key, title, file);
                                }
                            }, 700);
                        }
                    }
                });
